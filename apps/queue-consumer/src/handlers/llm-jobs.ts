/**
 * LLM jobs queue handler.
 *
 * Processes messages from ottoleveling-llm-jobs:
 * - generate_daily: KV pending flag → DO.generateDailyFromQueue(date) → KV ready/failed
 * - generate_bilan_*: NOT processed - acked with a warning (see below)
 *
 * Retry semantics: msg.attempts >= 5 → DLQ INSERT + ack (don't infinitely retry).
 * Otherwise msg.retry() with Cloudflare's exponential backoff.
 */
import type { MessageBatch } from '@cloudflare/workers-types';
import type { Env } from '../index';
import type { LlmJobMessage } from './types';
import { generateDailyQuests } from '../lib/generation';
import { emitAnalytics, persistLlmDlq } from '../lib/analytics';

export async function handleLlmJobsBatch(
  batch: MessageBatch<LlmJobMessage>,
  env: Env,
): Promise<void> {
  for (const msg of batch.messages) {
    const start = Date.now();
    try {
      const body = msg.body;
      if (body.type === 'generate_daily') {
        await generateDailyQuests(env, body.date);
        emitAnalytics(env, 'llm-jobs', body.type, 'success', Date.now() - start, msg.attempts);
        msg.ack();
      } else {
        // generate_bilan_evening / generate_bilan_weekly are not processed here.
        // Nothing sends generate_bilan_evening. generate_bilan_weekly is sent by
        // the daily-cycle workflow's evening-bilan-check step every Sunday at
        // 21:00 UTC, but the weekly bilan is actually generated by the
        // SystemAgent's weekly_bilan alarm (Sunday 20:00 UTC), so the message
        // is redundant. Ack so it does not retry its way into the DLQ.
        console.warn(`[llm-jobs] unhandled type: ${body.type} - acked without processing`);
        emitAnalytics(env, 'llm-jobs', body.type, 'success', Date.now() - start, msg.attempts);
        msg.ack();
      }
    } catch (err) {
      console.error(`[llm-jobs] error processing message:`, err);
      emitAnalytics(
        env,
        'llm-jobs',
        (msg.body as LlmJobMessage | null)?.type ?? 'unknown',
        msg.attempts >= 5 ? 'dlq' : 'retry',
        Date.now() - start,
        msg.attempts,
      );
      if (msg.attempts >= 5) {
        // Retries exhausted - persist to DLQ inspection table and ack.
        await persistLlmDlq(env, msg.body, msg.attempts, err);
        msg.ack();
      } else {
        msg.retry();
      }
    }
  }
}
